export function mount(stage, ctx) {
  const round = new Round(stage, ctx, { rounds: 8, pauseOk: 1500, pauseNo: 2600 });
  let last = null;

  round.start((view, api) => {
    let item = pick(PASSAGES);
    while (PASSAGES.length > 1 && item === last) item = pick(PASSAGES);
    last = item;

    const correct = item.a[0];
    const options = shuffle(item.a);
    let rightBtn = null;

    const buttons = options.map((text) => {
      const btn = el('button', { class: 'choice answer-choice', onClick: async () => {
        if (text === correct) {
          speak('נכון!');
          api.ok(btn);
        } else {
          api.no(btn);
          api.reveal(rightBtn);
          await wait(400);
          // Read the right answer out — after he's had his chance to read.
          speak(`התשובה הנכונה: ${correct}`, { rate: 0.85 });
        }
      } }, text);
      if (text === correct) rightBtn = btn;
      return btn;
    });

    // No speak() on the passage or the question. Reading it is the game.
    view.append(
      el('div', { class: 'passage', text: item.t }),
      el('div', { class: 'question', text: item.q }),
      el('div', { class: 'choices column' }, buttons),
    );
  });

  return () => round.stop();
}
