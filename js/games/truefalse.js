export function mount(stage, ctx) {
  // Level 3 gets the harder half as well as the easier one.
  const pool = ctx.profile.level >= 3
    ? STATEMENTS.filter((x) => x.lv === 3)
    : STATEMENTS.filter((x) => x.lv === 2);

  const round = new Round(stage, ctx, { rounds: 10, pauseOk: 1900, pauseNo: 3000 });
  let last = null;

  round.start((view, api) => {
    let item = pick(pool);
    while (pool.length > 1 && item === last) item = pick(pool);
    last = item;

    const ask = () => speak(item.s, { rate: 0.85 });
    ask();

    const why = el('div', { class: 'why' });

    const answer = async (said, btn) => {
      const right = said === item.t;
      // The explanation shows either way — being right is also a chance to learn.
      why.textContent = item.why || (item.t ? 'נכון!' : 'לא נכון');
      why.classList.add('show');

      if (right) {
        api.ok(btn);
        if (item.why) { await wait(600); speak(item.why, { rate: 0.9 }); }
      } else {
        api.no(btn);
        await wait(400);
        speak(`${item.t ? 'זה דווקא נכון' : 'זה לא נכון'}. ${item.why}`, { rate: 0.88 });
      }
    };

    const yes = el('button', { class: 'choice tf yes', onClick: () => answer(true, yes) },
      '✅ נכון');
    const no = el('button', { class: 'choice tf no', onClick: () => answer(false, no) },
      '❌ לא נכון');

    view.append(
      el('div', { class: 'statement', onClick: ask },
        item.s,
        el('small', { text: T.tapToHear }),
      ),
      el('div', { class: 'choices' }, yes, no),
      why,
    );
  });

  return () => round.stop();
}
